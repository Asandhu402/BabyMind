"""BabyMind's self-development engine.

Reads and writes BabyMind's own source tree with three non-negotiable rules:

1. Every change is preceded by a checkpoint of the files it can touch.
2. Every change is verified by a compile check and the project's own tests.
3. A change that fails verification is rolled back automatically and the
   rollback is recorded in an append-only audit log.

The engine is not an operating-system sandbox and does not claim to be. It keeps
BabyMind recoverable; it does not make arbitrary generated code safe to run.
"""
from __future__ import annotations

import hashlib
import json
import os
import secrets
import shutil
import sys
import time
from datetime import datetime, timezone
from pathlib import Path, PurePosixPath

from . import broker, runner
from .agents import require

STATE_DIRNAME = "state"
AUDIT_FILENAME = "dev-audit.jsonl"
CHECKPOINT_DIRNAME = "checkpoints"
KEEP_CHECKPOINTS = 20
MAX_FILES_PER_EDIT = 40
MAX_FILE_BYTES = 256 * 1024
MAX_TOTAL_BYTES = 2 * 1024 * 1024
MAX_SNAPSHOT_BYTES = 8 * 1024 * 1024

# Marks retry context that came from a proposer that could not be understood,
# as opposed to a patch that was applied and then failed verification. A
# proposer can only fix the first kind if it is told which one it hit.
PROPOSER_ERROR_PREFIX = "PROPOSER_ERROR: "

ALLOWED_SUFFIXES = {
    ".py", ".md", ".txt", ".json", ".toml", ".cfg", ".ini", ".yaml", ".yml",
    ".js", ".css", ".html", ".ps1", ".bat", ".sh", ".cmake", ".cpp", ".h", ".c",
    ".cs", ".java", ".ts", ".rs", ".go", ".sql",
}

# Directories that are never read into a checkpoint or written by the engine.
PROTECTED_PARTS = {
    ".git", ".hg", ".svn", "state", "__pycache__", ".pytest_cache", ".ruff_cache",
    ".mypy_cache", "node_modules", ".venv", "venv", "build", "dist", "out",
    ".next", "coverage", "target", "vendor",
}

PROTECTED_SUFFIXES = {
    ".key", ".sqlite3", ".sqlite", ".db", ".bmbak", ".gguf", ".exe", ".dll",
    ".pyd", ".so", ".dylib", ".pem", ".crt", ".pfx", ".p12",
}

GENERATED_NOTICE = "Generated by BabyMind self-development engine."


class SelfDevError(ValueError):
    """Raised when a self-development action is rejected or unavailable."""


def _flag_enabled() -> bool:
    return os.getenv("BABYMIND_SELF_DEVELOPMENT_ENABLED", "").strip().lower() in {"1", "true", "yes", "on"}


def _flag_disabled() -> bool:
    return os.getenv("BABYMIND_SELF_DEVELOPMENT_ENABLED", "").strip().lower() in {"0", "false", "no", "off"}


def dev_root() -> Path:
    """Return the source checkout BabyMind may develop."""
    if getattr(sys, "frozen", False):
        from . import packaged_dev
        try:
            return packaged_dev.workspace()
        except (OSError, packaged_dev.PackagedDevelopmentError) as error:
            raise SelfDevError(str(error)) from error
    configured = os.getenv("BABYMIND_DEV_ROOT", "").strip()
    if configured:
        try:
            root = Path(configured).expanduser().resolve(strict=True)
        except OSError as error:
            raise SelfDevError("BABYMIND_DEV_ROOT must point to an existing folder.") from error
    else:
        root = Path(__file__).resolve().parents[2]
    if not (root / "src" / "babymind").is_dir():
        raise SelfDevError("The development root does not contain src/babymind.")
    return root


def available() -> bool:
    """True when a developable source checkout is present."""
    try:
        dev_root()
    except SelfDevError:
        return False
    return True


def selfdev_enabled() -> bool:
    if _flag_disabled():
        return False
    if _flag_enabled():
        return available()
    # A source checkout is a development environment by definition.
    return available()


def _state_dir(root: Path) -> Path:
    path = root / STATE_DIRNAME
    path.mkdir(parents=True, exist_ok=True)
    return path


def now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# --------------------------------------------------------------------------- paths

def _normalise(path: str) -> PurePosixPath:
    if not isinstance(path, str) or not path.strip():
        raise SelfDevError("Every edit needs a relative file path.")
    raw = path.strip().replace("\\", "/")
    if len(raw) > 240 or "\x00" in raw:
        raise SelfDevError("A file path is empty, too long, or contains a NUL byte.")
    candidate = PurePosixPath(raw)
    if candidate.is_absolute() or candidate.drive or ":" in raw:
        raise SelfDevError(f"Paths must be relative to the project: {path}")
    if any(part in {"", ".", ".."} for part in candidate.parts):
        raise SelfDevError(f"Paths cannot contain '.', '..', or empty segments: {path}")
    if PROTECTED_PARTS & set(candidate.parts) or ".babymind-development-workspace.json" in candidate.parts:
        raise SelfDevError(f"Protected path: {path}")
    if candidate.suffix.lower() in PROTECTED_SUFFIXES:
        raise SelfDevError(f"Binary, key, or database files are never edited: {path}")
    if candidate.suffix.lower() not in ALLOWED_SUFFIXES:
        raise SelfDevError(f"File type is not editable: {path}")
    return candidate


def resolve_path(root: Path, relative: str) -> Path:
    """Resolve a project-relative path, refusing anything outside the root."""
    candidate = _normalise(relative)
    resolved_root = root.resolve()
    target = resolved_root
    # Inspect the original components before resolving: resolve() erases the
    # symlink evidence, including links to protected paths inside the root.
    for part in candidate.parts:
        target = target / part
        if target.is_symlink():
            raise SelfDevError("Symbolic links are not supported in the development workspace.")
    resolved_target = target.resolve()
    if not resolved_target.is_relative_to(resolved_root):
        raise SelfDevError("The resolved path is outside the development root.")
    return resolved_target


# --------------------------------------------------------------------------- audit

BASELINE_FILENAME = "test-baseline.json"


def _baseline_path(root: Path) -> Path:
    return _state_dir(root) / BASELINE_FILENAME


def load_test_baseline() -> dict | None:
    """Return the recorded pre-existing test problems, if any."""
    root = dev_root()
    path = _baseline_path(root)
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def _test_problem_ids(result: dict) -> set[str]:
    """Extract unittest failure/error headings from either captured output stream.

    The suite summary is parsed from stdout + stderr. Keep this evidence parser
    consistent: unittest output can be redirected by a runner or test harness,
    and looking only at stderr makes a completed failing suite appear incomplete.
    """
    import re
    output = "\\n".join((result.get("stderr") or "", result.get("stdout") or ""))
    return set(re.findall(r"^(?:FAIL|ERROR): (.+)$", output, re.MULTILINE))


def _suite_diagnosis(result: dict) -> str:
    """One line of evidence explaining why a suite result was rejected.

    "_suite_completed" has three independent reasons to say no, and a hosted run
    gives no way to re-run the suite and find out which one fired. Report the
    counters that decide it, so a failure names its own cause.
    """
    summary = result.get("summary") or {}
    return (
        f"ran={summary.get('ran', 0)} skipped={summary.get('skipped', 0)} "
        f"problems={summary.get('problems', 0)} identified={len(_test_problem_ids(result))} "
        f"exit={result.get('exit_code')} timed_out={result.get('timed_out')} "
        f"truncated={result.get('truncated')} output_chars={len(result.get('stderr') or '') + len(result.get('stdout') or '')}"
    )


def _suite_completed(result: dict) -> bool:
    """Reject empty, interrupted and unaccounted-for test runs.

    An ordinary unittest exit of 1 can be a known failing baseline. A timeout,
    crash or an empty/all-skipped suite is not evidence of verification.
    """
    summary = result["summary"]
    if summary["ran"] <= summary.get("skipped", 0) or result.get("timed_out"):
        return False
    if summary["problems"] and len(_test_problem_ids(result)) < summary["problems"]:
        return False  # Missing/truncated failure evidence cannot be compared.
    return bool(result.get("ok")) or (result.get("exit_code") == 1 and summary["problems"] > 0)


def _record_baseline(root: Path, summary: dict) -> dict:
    """Keep the lowest problem count ever observed as the expected baseline."""
    current = summary.get("problems", summary.get("failures", 0) + summary.get("errors", 0))
    existing = load_test_baseline()
    if existing is not None and existing.get("problems", 0) <= current:
        return existing
    record = {
        "problems": current,
        "failures": summary.get("failures", 0),
        "errors": summary.get("errors", 0),
        "ran": summary.get("ran", 0),
        "updated_at": now(),
        "note": "Pre-existing test problems tolerated by the self-development engine.",
    }
    _baseline_path(root).write_text(json.dumps(record, indent=2), encoding="utf-8")
    return record


def _audit_path(root: Path) -> Path:
    return _state_dir(root) / AUDIT_FILENAME


def _append_audit(root: Path, record: dict) -> dict:
    path = _audit_path(root)
    previous = ""
    if path.exists():
        try:
            with path.open("r", encoding="utf-8") as handle:
                for line in handle:
                    if line.strip():
                        previous = json.loads(line).get("hash", "")
        except (OSError, json.JSONDecodeError):
            previous = ""
    entry = {**record, "at": now(), "previous": previous}
    entry["hash"] = _sha256(json.dumps(entry, sort_keys=True, separators=(",", ":")).encode("utf-8"))
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(entry, ensure_ascii=False) + "\n")
        handle.flush()
        os.fsync(handle.fileno())
    return entry


def audit_entries(limit: int = 50) -> list[dict]:
    root = dev_root()
    path = _audit_path(root)
    if not path.exists():
        return []
    entries: list[dict] = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                try:
                    entries.append(json.loads(line))
                except json.JSONDecodeError:
                    continue
    return entries[-max(1, min(int(limit), 500)):][::-1]


def verify_audit_chain() -> dict:
    """Check that the append-only audit log has not been rewritten."""
    root = dev_root()
    path = _audit_path(root)
    entries = [entry for entry in audit_entries(5000)][::-1]
    previous = ""
    for entry in entries:
        body = {key: value for key, value in entry.items() if key != "hash"}
        expected = _sha256(json.dumps(body, sort_keys=True, separators=(",", ":")).encode("utf-8"))
        if entry.get("hash") != expected or entry.get("previous", "") != previous:
            return {"valid": False, "entries": len(entries), "broken_at": entry.get("at")}
        previous = entry["hash"]
    return {"valid": True, "entries": len(entries)}


# --------------------------------------------------------------------------- checkpoints

def _project_files(root: Path) -> list[Path]:
    files: list[Path] = []
    for directory, subdirectories, names in os.walk(root):
        current = Path(directory)
        subdirectories[:] = sorted(
            name for name in subdirectories
            if name not in PROTECTED_PARTS and not (current / name).is_symlink()
        )
        for name in sorted(names):
            path = current / name
            if path.is_symlink() or path.suffix.lower() in PROTECTED_SUFFIXES:
                continue
            if path.suffix.lower() not in ALLOWED_SUFFIXES:
                continue
            files.append(path)
    return files


def _checkpoint_root(root: Path) -> Path:
    path = _state_dir(root) / CHECKPOINT_DIRNAME
    path.mkdir(parents=True, exist_ok=True)
    return path


def list_checkpoints(limit: int = 20) -> list[dict]:
    root = dev_root()
    directory = _checkpoint_root(root)
    records = []
    for entry in directory.iterdir():
        manifest = entry / "manifest.json"
        if not manifest.is_file():
            continue
        try:
            records.append(json.loads(manifest.read_text(encoding="utf-8")))
        except (OSError, json.JSONDecodeError):
            continue
    records.sort(key=lambda item: item.get("created_at", ""), reverse=True)
    return records[:max(1, min(int(limit), 200))]


def checkpoint(label: str = "", *, reason: str = "", extra_paths: list[str] | None = None) -> dict:
    """Snapshot the project files so any later change can be reverted."""
    root = dev_root()
    if not selfdev_enabled():
        raise SelfDevError("Self-development is disabled by configuration.")
    identifier = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S") + "-" + secrets.token_hex(3)
    directory = _checkpoint_root(root) / identifier
    files_dir = directory / "files"
    files_dir.mkdir(parents=True, exist_ok=False)

    entries: dict[str, dict] = {}
    total = 0
    skipped = []
    candidates = []
    # Prioritise explicitly edited files so unrelated project files cannot
    # exhaust the snapshot budget before the targets are backed up.
    for relative_raw in extra_paths or []:
        try:
            candidates.append(resolve_path(root, relative_raw))
        except SelfDevError:
            skipped.append(relative_raw)
    candidates.extend(_project_files(root))
    for path in dict.fromkeys(candidates):
        if not path.is_file():
            continue
        data = path.read_bytes()
        if total + len(data) > MAX_SNAPSHOT_BYTES:
            skipped.append(str(path.relative_to(root)))
            continue
        relative = path.relative_to(root).as_posix()
        destination = files_dir / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, destination)
        entries[relative] = {"sha256": _sha256(data), "bytes": len(data)}
        total += len(data)

    record = {
        "id": identifier,
        "label": (label or "checkpoint")[:160],
        "reason": (reason or "")[:400],
        "created_at": now(),
        "files": entries,
        "file_count": len(entries),
        "bytes": total,
        "skipped": skipped[:20],
        "format": "babymind-checkpoint-v1",
    }
    (directory / "manifest.json").write_text(
        json.dumps(record, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    _append_audit(root, {"action": "checkpoint", "checkpoint": identifier,
                         "label": record["label"], "files": len(entries), "bytes": total})
    _prune_checkpoints(root)
    return record


def _prune_checkpoints(root: Path) -> None:
    records = list_checkpoints(limit=500)
    for record in records[KEEP_CHECKPOINTS:]:
        shutil.rmtree(_checkpoint_root(root) / record["id"], ignore_errors=True)


def _load_checkpoint(root: Path, checkpoint_id: str) -> dict:
    if not isinstance(checkpoint_id, str) or not checkpoint_id.strip():
        raise SelfDevError("A checkpoint id is required.")
    if any(ch not in "0123456789abcdef-" for ch in checkpoint_id.lower()):
        raise SelfDevError("Invalid checkpoint id.")
    directory = _checkpoint_root(root) / checkpoint_id
    manifest = directory / "manifest.json"
    if not manifest.is_file():
        raise SelfDevError(f"Checkpoint not found: {checkpoint_id}")
    record = json.loads(manifest.read_text(encoding="utf-8"))
    record["_directory"] = str(directory)
    return record


def rollback(checkpoint_id: str, *, agent_id: str = "BM-47", require_permission: bool = True,
             _only_paths: set[str] | None = None, _created_paths: list[str] | None = None,
             _expected_hashes: dict[str, str] | None = None) -> dict:
    """Restore every file recorded in a checkpoint and drop files it created.

    ``require_permission`` is False only for the engine's own automatic
    rollback, which is a safety action rather than an agent action.
    """
    root = dev_root()
    if require_permission:
        require("recovery.rollback", agent_id)
    record = _load_checkpoint(root, checkpoint_id)
    directory = Path(record["_directory"])
    # Do not silently overwrite a later user's change to an edited path. Check
    # the whole set first, before restoring any file. This is not a lock and
    # cannot eliminate races with a concurrent writer after the check.
    if _expected_hashes is not None:
        for relative in _only_paths or set():
            target = resolve_path(root, relative)
            if not target.is_file() or _sha256(target.read_bytes()) != _expected_hashes.get(relative):
                raise SelfDevError(f"{relative} changed after the edit; manual recovery is required.")
    restored, created_removed = [], []
    for relative, meta in record["files"].items():
        if _only_paths is not None and relative not in _only_paths:
            continue
        source = directory / "files" / relative
        if not source.is_file():
            if _only_paths is not None:
                raise SelfDevError(f"Checkpoint is missing the backup for {relative}.")
            continue
        target = resolve_path(root, relative)
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_name(f".{target.name}.bmrestore-{secrets.token_hex(3)}")
        shutil.copy2(source, temporary)
        os.replace(temporary, target)
        restored.append(relative)
    for relative in record.get("created", []) if _created_paths is None else _created_paths:
        if _only_paths is not None and relative not in _only_paths:
            continue
        try:
            target = resolve_path(root, relative)
        except SelfDevError:
            continue
        if target.is_file():
            target.unlink()
            created_removed.append(relative)
    _append_audit(root, {"action": "rollback", "checkpoint": checkpoint_id,
                         "restored": len(restored), "removed": len(created_removed)})
    return {
        "status": "rolled_back",
        "checkpoint_id": checkpoint_id,
        "restored_files": restored,
        "removed_files": created_removed,
        "checkpoint_created_at": record.get("created_at"),
    }


# --------------------------------------------------------------------------- edits

def preview_edits(edits: list[dict]) -> list[dict]:
    """Return a reviewable summary and unified diff for proposed edits."""
    root = dev_root()
    if not isinstance(edits, list) or not edits:
        raise SelfDevError("Provide at least one edit.")
    if len(edits) > MAX_FILES_PER_EDIT:
        raise SelfDevError(f"At most {MAX_FILES_PER_EDIT} files can change in one transaction.")
    import difflib

    reviewed = []
    seen: set[str] = set()
    total = 0
    for item in edits:
        if not isinstance(item, dict) or set(item) != {"path", "content"}:
            raise SelfDevError("Each edit must contain exactly 'path' and 'content'.")
        relative = _normalise(item["path"])
        key = relative.as_posix()
        if key in seen:
            raise SelfDevError(f"The same path appears twice: {key}")
        seen.add(key)
        content = item["content"]
        if not isinstance(content, str):
            raise SelfDevError(f"Content must be text: {key}")
        if "\x00" in content:
            raise SelfDevError(f"Content contains a NUL byte: {key}")
        encoded = content.encode("utf-8")
        if len(encoded) > MAX_FILE_BYTES:
            raise SelfDevError(f"{key} exceeds the {MAX_FILE_BYTES // 1024} KB per-file limit.")
        total += len(encoded)
        if total > MAX_TOTAL_BYTES:
            raise SelfDevError("This transaction exceeds the total size limit.")
        target = resolve_path(root, key)
        previous = target.read_text(encoding="utf-8") if target.is_file() else ""
        diff = "".join(difflib.unified_diff(
            previous.splitlines(keepends=True), content.splitlines(keepends=True),
            fromfile=f"a/{key}", tofile=f"b/{key}",
        ))
        reviewed.append({
            "path": key,
            "exists": target.is_file(),
            "bytes_before": len(previous.encode("utf-8")),
            "bytes_after": len(encoded),
            "diff": diff[:20_000],
            "content": content,
        })
    return reviewed


def _worktree_preverify(root: Path, reviewed: list[dict], test_timeout: int) -> None:
    """Opt-in worktree isolation: apply and verify the change in a disposable
    git worktree first; the primary checkout is untouched if it fails."""
    from . import worktree
    if not worktree.worktree_enabled() or not worktree.is_git_repo(root):
        return
    tree = worktree.create_worktree(root)
    try:
        for item in reviewed:
            target = resolve_path(tree, item["path"])
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(item["content"], encoding="utf-8")
        compile_result = broker.run_compile_check(tree, sandbox_mode=sandbox_mode())
        if not compile_result["ok"]:
            raise SelfDevError("Worktree pre-verification failed at compile; the primary "
                               "checkout was not modified. " + (compile_result.get("stderr") or "")[-1000:])
        tests_result = broker.run_unit_tests(tree, timeout=test_timeout, sandbox_mode=sandbox_mode())
        if not _suite_completed(tests_result) or not tests_result["summary"].get("passed"):
            raise SelfDevError("Worktree pre-verification failed tests; the primary checkout "
                               "was not modified. " + (tests_result.get("stderr") or "")[-1000:])
    finally:
        worktree.discard_worktree(root, tree)


def apply_edits(
    edits: list[dict],
    *,
    reason: str = "",
    agent_id: str = "BM-03",
    verify: bool = True,
    test_timeout: int = 300,
) -> dict:
    """Apply a validated multi-file transaction and verify it, or roll it back."""
    if getattr(sys, "frozen", False) and not verify:
        raise SelfDevError("Packaged source edits must be verified.")
    root = dev_root()
    require("repo.write", agent_id)
    if not selfdev_enabled():
        raise SelfDevError("Self-development is disabled by configuration.")
    reviewed = preview_edits(edits)
    _worktree_preverify(root, reviewed, test_timeout)
    if sandbox_mode() == "require":
        from . import sandbox
        try:
            evidence = sandbox.self_test(root)
        except Exception as error:
            raise SelfDevError(f"Sandbox boundary probe failed; no edit was applied: {error}") from error
        if not evidence.get("verified"):
            raise SelfDevError("Sandbox boundary was not verified; no edit was applied: "
                               + str(evidence.get("reason") or "one or more probes failed"))
    # Establish the expected baseline BEFORE the change lands, so a failure the
    # change introduces can never be mistaken for a pre-existing one.
    baseline = load_test_baseline()
    before_summary = None
    before_problems: set[str] = set()
    if verify:
        before = broker.run_unit_tests(root, timeout=test_timeout, sandbox_mode=sandbox_mode())
        if not _suite_completed(before):
            raise SelfDevError(
                "The pre-edit test suite did not complete with runnable tests; no edit was applied. "
                f"[{_suite_diagnosis(before)}]"
            )
        before_summary = before["summary"]
        before_problems = _test_problem_ids(before)
        baseline = _record_baseline(root, before_summary)
    snapshot = checkpoint(
        label=f"pre-apply: {reason or 'self-development'}",
        reason=reason,
        extra_paths=[item["path"] for item in reviewed],
    )
    created = [item["path"] for item in reviewed if not item["exists"]]
    missing_backups = [item["path"] for item in reviewed
                       if item["exists"] and item["path"] not in snapshot["files"]]
    if missing_backups:
        raise SelfDevError("Cannot edit files missing from the checkpoint: " + ", ".join(missing_backups))

    # Record the intended paths before writing so the checkpoint remains useful
    # if the process is interrupted during the transaction.
    manifest_path = Path(snapshot["_directory"] if "_directory" in snapshot
                         else _checkpoint_root(root) / snapshot["id"]) / "manifest.json"
    data = json.loads(manifest_path.read_text(encoding="utf-8"))
    data["created"] = created
    data["applied"] = [item["path"] for item in reviewed]
    manifest_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    written: list[str] = []
    expected_hashes = {item["path"]: _sha256(item["content"].encode("utf-8")) for item in reviewed}
    temporary: Path | None = None
    try:
        for item in reviewed:
            target = resolve_path(root, item["path"])
            target.parent.mkdir(parents=True, exist_ok=True)
            if item["exists"]:
                expected = snapshot["files"][item["path"]]["sha256"]
                if not target.is_file() or _sha256(target.read_bytes()) != expected:
                    raise SelfDevError(f"{item['path']} changed after the checkpoint; refusing to overwrite it.")
            temporary = target.with_name(f".{target.name}.bmedit-{secrets.token_hex(3)}")
            temporary.write_text(item["content"], encoding="utf-8")
            if item["exists"]:
                os.replace(temporary, target)
                written.append(item["path"])
            else:
                # Atomic no-overwrite publication protects files that appeared
                # after preview. The temporary file is on the same filesystem.
                os.link(temporary, target)
                written.append(item["path"])
                temporary.unlink()
            temporary = None
    except Exception as error:
        cleanup_error = None
        if temporary is not None:
            try:
                temporary.unlink(missing_ok=True)
            except OSError as cleanup_failure:
                cleanup_error = cleanup_failure
        try:
            rollback(snapshot["id"], agent_id=agent_id, require_permission=False,
                     _only_paths=set(written), _created_paths=created,
                     _expected_hashes=expected_hashes)
        except Exception as rollback_error:
            raise SelfDevError(
                f"Writing failed and automatic rollback failed: {rollback_error}. "
                f"Manual recovery may be needed from checkpoint {snapshot['id']}."
            ) from error
        if cleanup_error:
            raise SelfDevError(f"Writing failed and edits were reverted, but a temporary file could not be removed: {cleanup_error}") from error
        _append_audit(root, {"action": "apply_failed", "error": str(error),
                             "checkpoint": snapshot["id"], "written": written})
        raise SelfDevError(f"Writing failed and was reverted: {error}") from error

    try:
        purge_bytecode(root)
        compile_result = broker.run_compile_check(root, sandbox_mode=sandbox_mode())
        tests_result = None
        failure = ""
        if not compile_result["ok"]:
            failure = "compile check failed"
        elif verify:
            purge_bytecode(root)  # never verify against stale bytecode
            tests_result = broker.run_unit_tests(root, timeout=test_timeout, sandbox_mode=sandbox_mode())
            summary = tests_result["summary"]
            # A pre-existing broken test in this environment must not block every
            # change forever; only a *new* problem counts as a regression.
            if not _suite_completed(tests_result):
                failure = f"test suite did not complete with runnable tests [{_suite_diagnosis(tests_result)}]"
            elif (summary["ran"] < before_summary["ran"]
                  or summary["ran"] - summary.get("skipped", 0)
                  < before_summary["ran"] - before_summary.get("skipped", 0)):
                failure = "test suite regressed: fewer tests ran or more tests were skipped"
            elif summary["problems"] > (baseline or {}).get("problems", 0):
                failure = (
                    f"test suite regressed: {summary['problems']} problems "
                    f"(baseline {(baseline or {}).get('problems', 0)})"
                )
            elif _test_problem_ids(tests_result) - before_problems:
                failure = "test suite regressed: a previously passing test now fails"
            else:
                baseline = _record_baseline(root, summary)
    except Exception as error:
        try:
            rollback(snapshot["id"], agent_id=agent_id, require_permission=False,
                     _only_paths=set(written), _created_paths=created,
                     _expected_hashes=expected_hashes)
        except Exception as rollback_error:
            raise SelfDevError(
                f"Verification failed and automatic rollback failed: {rollback_error}. "
                f"Manual recovery may be needed from checkpoint {snapshot['id']}."
            ) from error
        raise SelfDevError(f"Verification failed and the change was reverted: {error}") from error

    if failure:
        try:
            restore = rollback(snapshot["id"], agent_id=agent_id, require_permission=False,
                               _only_paths=set(written), _created_paths=created,
                               _expected_hashes=expected_hashes)
        except Exception as rollback_error:
            raise SelfDevError(
                f"{failure}; automatic rollback failed: {rollback_error}. "
                f"Manual recovery may be needed from checkpoint {snapshot['id']}."
            ) from rollback_error
        _append_audit(root, {
            "action": "auto_rollback", "reason": failure, "checkpoint": snapshot["id"],
            "applied": [item["path"] for item in reviewed], "agent": agent_id,
        })
        return {
            "status": "rolled_back",
            "reason": failure,
            "checkpoint_id": snapshot["id"],
            "compile": compile_result,
            "tests": tests_result,
            "sandboxed": bool(tests_result and tests_result.get("sandboxed")),
            "rollback": restore,
            "notice": "The change failed verification and was reverted automatically.",
        }

    _append_audit(root, {
        "action": "applied", "checkpoint": snapshot["id"], "files": written,
        "reason": reason, "agent": agent_id, "verified": verify,
        "tests_ran": (tests_result or {}).get("summary", {}).get("ran", 0),
    })
    return {
        "status": "applied",
        "source_scope": "staged-copy" if getattr(sys, "frozen", False) else "source-checkout",
        "updates_running_app": False if getattr(sys, "frozen", False) else None,
        "checkpoint_id": snapshot["id"],
        "files": [{"path": item["path"], "bytes_before": item["bytes_before"],
                   "bytes_after": item["bytes_after"], "created": not item["exists"]}
                  for item in reviewed],
        "compile": compile_result,
        "tests": tests_result,
        "baseline": load_test_baseline(),
        "sandboxed": bool(tests_result and tests_result.get("sandboxed")),
        "notice": (
            "Change applied and verified against the project's own test suite baseline. "
            f"Roll back with checkpoint {snapshot['id']} if needed."
            + (" This is a staged source copy; the running packaged app is unchanged."
               if getattr(sys, "frozen", False) else "")
        ),
    }


def purge_bytecode(root: Path) -> int:
    """Delete source/test bytecode caches to avoid stale verification.

    Python validates a cached .pyc with the source's mtime (whole seconds) and
    size. A same-size edit inside the same second would otherwise be verified
    against the previous bytecode.
    """
    removed = 0
    # Verification imports only source and test modules. Do not touch caches in
    # user environments, vendor trees, state, or other unrelated directories.
    for scope in (root / "src", root / "tests"):
        if not scope.is_dir() or scope.is_symlink():
            continue
        for directory, subdirectories, names in os.walk(scope):
            current = Path(directory)
            if "__pycache__" in subdirectories:
                target = current / "__pycache__"
                if not target.is_symlink():
                    shutil.rmtree(target, ignore_errors=True)
                    removed += 1
                subdirectories.remove("__pycache__")
            subdirectories[:] = [name for name in subdirectories
                                 if name not in PROTECTED_PARTS and not (current / name).is_symlink()]
            for name in names:
                if name.endswith(".pyc"):
                    try:
                        (current / name).unlink()
                        removed += 1
                    except OSError:
                        pass
    return removed


