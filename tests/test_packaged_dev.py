"""Packaged source staging tests; these do not test runtime activation."""
from __future__ import annotations

import os
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from babymind import packaged_dev, selfdev


class PackagedDevTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.package = self.root / "package"
        seed = self.package / "dev-source-seed"
        (seed / "src" / "babymind").mkdir(parents=True)
        (seed / "src" / "babymind" / "core.py").write_text("VALUE = 1\n")
        (seed / "tests").mkdir()
        helper = self.package / "dev-python" / "bin" / "python3"
        helper.parent.mkdir(parents=True)
        helper.write_text("fixture")
        helper.chmod(0o700)
        self.env = patch.dict(os.environ, {"BABYMIND_HOME": str(self.root / "data")})
        self.env.start()
        self.app = patch.object(packaged_dev, "app_directory", return_value=self.package)
        self.app.start()

    def tearDown(self):
        self.app.stop()
        self.env.stop()
        self.temp.cleanup()

    def test_workspace_created_once_without_overwriting_edits(self):
        root = packaged_dev.workspace()
        path = root / "src" / "babymind" / "core.py"
        self.assertEqual(path.read_text(), "VALUE = 1\n")
        path.write_text("VALUE = 9\n")
        self.assertEqual(packaged_dev.workspace(), root)
        self.assertEqual(path.read_text(), "VALUE = 9\n")
        self.assertEqual((self.package / "dev-source-seed/src/babymind/core.py").read_text(), "VALUE = 1\n")

    def test_changed_package_seed_does_not_overwrite_existing_workspace(self):
        root = packaged_dev.workspace()
        path = root / "src/babymind/core.py"
        path.write_text("user edits\n")
        (self.package / "dev-source-seed/src/babymind/core.py").write_text("new version\n")
        with self.assertRaisesRegex(packaged_dev.PackagedDevelopmentError, "different package version"):
            packaged_dev.workspace()
        self.assertEqual(path.read_text(), "user edits\n")

    def test_existing_unmanaged_workspace_is_never_overwritten(self):
        root = self.root / "data" / "development-source"
        root.mkdir(parents=True)
        (root / "important.txt").write_text("keep")
        with self.assertRaisesRegex(packaged_dev.PackagedDevelopmentError, "not a recognised"):
            packaged_dev.workspace()
        self.assertEqual((root / "important.txt").read_text(), "keep")

    def test_symbolic_links_in_seed_are_rejected(self):
        (self.package / "dev-source-seed/tests/escape.py").symlink_to(self.root / "private")
        with self.assertRaisesRegex(packaged_dev.PackagedDevelopmentError, "symbolic link"):
            packaged_dev.workspace()
        self.assertFalse((self.root / "data" / "development-source").exists())

    def test_frozen_mode_cannot_target_arbitrary_checkout_or_disable_sandbox(self):
        with patch.object(sys, "frozen", True, create=True), \
             patch.dict(os.environ, {"BABYMIND_DEV_ROOT": str(self.root), "BABYMIND_SANDBOX": "off"}):
            root = selfdev.dev_root()
            self.assertEqual(root, (self.root / "data/development-source").resolve())
            self.assertEqual(selfdev.sandbox_mode(), "require")
            with self.assertRaisesRegex(selfdev.SelfDevError, "Protected path"):
                selfdev.preview_edits([{"path": ".babymind-development-workspace.json", "content": "{}"}])


if __name__ == "__main__":
    unittest.main()


class SeedContentsTests(unittest.TestCase):
    """The packaged seed must be a complete source copy.

    `verify_packaged_staging` runs the project's own suite inside the seeded
    copy, so a top-level file the suite reads cannot be left out of the seed.
    """

    @classmethod
    def setUpClass(cls):
        import importlib.util
        script = Path(__file__).resolve().parents[1] / "scripts" / "build_packaged_dev.py"
        spec = importlib.util.spec_from_file_location("build_packaged_dev", script)
        cls.module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(cls.module)

    def test_every_top_level_file_except_secrets_is_copied(self):
        with tempfile.TemporaryDirectory() as directory:
            repo = Path(directory)
            for name in ("pyproject.toml", "install-linux.sh", "install-and-run-linux.sh",
                         "build-linux.sh", "run_desktop.py", "README.md", "LICENSE",
                         "NOTICE", "SECURITY.md", ".gitmodules"):
                (repo / name).write_text("fixture\n")
            (repo / "BabyMind.spec").write_text("# generated by PyInstaller\n")
            (repo / ".env").write_text("SECRET=1\n")
            (repo / ".env.local").write_text("SECRET=1\n")
            (repo / "src").mkdir()
            (repo / "notes.md").symlink_to(repo / "README.md")
            copied = {path.name for path in self.module.seed_root_files(repo)}
        self.assertEqual(copied, {"pyproject.toml", "install-linux.sh", "install-and-run-linux.sh",
                                  "build-linux.sh", "run_desktop.py", "README.md", "LICENSE",
                                  "NOTICE", "SECURITY.md", ".gitmodules"})

    def test_real_checkout_supplies_files_the_suite_reads(self):
        repo = Path(__file__).resolve().parents[1]
        copied = {path.name for path in self.module.seed_root_files(repo)}
        for required in ("pyproject.toml", "README.md", "install-linux.sh",
                         "install-and-run-linux.sh", "build-linux.sh", "run_desktop.py"):
            self.assertIn(required, copied, f"{required} is missing from the packaged source seed")
        self.assertNotIn(".env", copied)


class StagingVerdictTests(unittest.TestCase):
    """The packaged staging check accepts verified, non-regressing edits only."""

    def good(self, **overrides):
        result = {
            "status": "applied",
            "sandboxed": True,
            "source_scope": "staged-copy",
            "tests": {"summary": {"ran": 420, "skipped": 37, "problems": 4}},
            "baseline": {"problems": 4},
        }
        result.update(overrides)
        return result

    def test_verified_edit_with_tolerated_environment_problems_is_accepted(self):
        self.assertEqual(packaged_dev.staging_problems(self.good()), [])

    def test_pristine_suite_is_accepted(self):
        result = self.good(tests={"summary": {"ran": 420, "skipped": 2, "problems": 0}},
                           baseline={"problems": 0})
        self.assertEqual(packaged_dev.staging_problems(result), [])

    def test_rolled_back_edit_is_rejected(self):
        problems = packaged_dev.staging_problems(self.good(status="rolled_back", reason="tests failed"))
        self.assertTrue(any("rolled_back" in problem and "tests failed" in problem for problem in problems))

    def test_unsandboxed_verification_is_rejected(self):
        problems = packaged_dev.staging_problems(self.good(sandboxed=False))
        self.assertTrue(any("not sandboxed" in problem for problem in problems))

    def test_non_staged_scope_is_rejected(self):
        problems = packaged_dev.staging_problems(self.good(source_scope="source-checkout"))
        self.assertTrue(any("source-checkout" in problem for problem in problems))

    def test_empty_or_all_skipped_suite_is_rejected(self):
        for summary in ({"ran": 0, "skipped": 0, "problems": 0}, {"ran": 12, "skipped": 12, "problems": 0}):
            problems = packaged_dev.staging_problems(self.good(tests={"summary": summary}))
            self.assertTrue(any("ran no tests" in problem for problem in problems), summary)

    def test_new_test_problems_are_rejected(self):
        result = self.good(tests={"summary": {"ran": 420, "skipped": 37, "problems": 9}},
                           baseline={"problems": 4})
        problems = packaged_dev.staging_problems(result)
        self.assertTrue(any("regressed" in problem for problem in problems))
